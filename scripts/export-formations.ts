// Export the animated cultural formations as files for the show pipeline.
//
//   npx vite-node scripts/export-formations.ts -- [outDir] [drones] [fps]
//   (defaults: ../Formations, 500 drones, 24 fps)
//
// Per formation, into <outDir>/<id>/:
//   <id>.points.json   600-point cloud at t=0, in the format of the
//                      Formation Asset Spec: metres, origin at the
//                      formation centre, Y up, outline-first for 2D figures,
//                      plus sRGB colours.
//   <id>.preview.svg   front view of t=0 as coloured dots (for decks/clients).
//   <id>.skybrush.zip  one CSV per drone for one loop, in Skybrush Studio
//                      for Blender's "zipped CSV" import format (Formations
//                      panel docs): Time_msec,x_m,y_m,z_m,Red,Green,Blue,
//                      Z up, metres, colours in LINEAR space (0-255).
//   <id>.formation.csv the t=0 frame as a static formation, Skybrush's
//                      "static CSV" import: Name,x_m,y_m,z_m,Red,Green,Blue.
//                      Both imports work on the free community server.
// And <outDir>/REPORT.md: max speed and minimum separation per formation —
// what has to change before any of it is flight-ready.
//
// These are VISUAL references from the website's concept renders. They are
// not flight plans: nothing here is collision-checked or speed-limited.
// That is Skybrush's job, after design.

import { mkdirSync, writeFileSync } from "node:fs";
import { crc32, deflateRawSync } from "node:zlib";
import { join, resolve } from "node:path";
import { CULTURAL, SHOW_ALT } from "../src/lib/cultural";

const args = process.argv.slice(2).filter((a) => a !== "--");
const OUT = resolve(args[0] ?? "../Formations");
const N = Number(args[1] ?? 500);
const FPS = Number(args[2] ?? 24);
const CLOUD = 600;

/** Minimal zip writer (deflate), so the export is import-ready as is. */
function zip(files: { name: string; data: Buffer }[]): Buffer {
  const chunks: Buffer[] = [];
  const central: Buffer[] = [];
  let offset = 0;
  for (const f of files) {
    const name = Buffer.from(f.name);
    const body = deflateRawSync(f.data);
    const crc = crc32(f.data) >>> 0;
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0, 6);
    local.writeUInt16LE(8, 8);
    local.writeUInt32LE(0, 10);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(body.length, 18);
    local.writeUInt32LE(f.data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    chunks.push(local, name, body);
    const c = Buffer.alloc(46);
    c.writeUInt32LE(0x02014b50, 0);
    c.writeUInt16LE(20, 4);
    c.writeUInt16LE(20, 6);
    c.writeUInt16LE(0, 8);
    c.writeUInt16LE(8, 10);
    c.writeUInt32LE(0, 12);
    c.writeUInt32LE(crc, 16);
    c.writeUInt32LE(body.length, 20);
    c.writeUInt32LE(f.data.length, 24);
    c.writeUInt16LE(name.length, 28);
    c.writeUInt32LE(offset, 42);
    central.push(c, name);
    offset += 30 + name.length + body.length;
  }
  const cd = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(cd.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...chunks, cd, end]);
}

/** Linear 0..1 -> linear 0..255 (Skybrush reads CSV colours as linear). */
const lin255 = (c: number) => Math.round(255 * Math.max(0, Math.min(1, c)));

const toSrgb = (c: number) => {
  const v = Math.max(0, Math.min(1, c));
  return Math.round(255 * (v <= 0.0031308 ? 12.92 * v : 1.055 * Math.pow(v, 1 / 2.4) - 0.055));
};

function centreOf(pos: Float32Array, n: number) {
  let x = 0, y = 0, z = 0;
  for (let i = 0; i < n; i++) {
    x += pos[i * 3];
    y += pos[i * 3 + 1];
    z += pos[i * 3 + 2];
  }
  return [x / n, y / n, z / n];
}

function minSeparation(pos: Float32Array, col: Float32Array, n: number): number {
  // Lit drones only: a dark drone parked inside a figure is a choreography
  // detail, but every drone still needs its own airspace, so count all.
  void col;
  let best = Infinity;
  for (let i = 0; i < n; i++) {
    const xi = pos[i * 3], yi = pos[i * 3 + 1], zi = pos[i * 3 + 2];
    for (let j = i + 1; j < n; j++) {
      const d = (xi - pos[j * 3]) ** 2 + (yi - pos[j * 3 + 1]) ** 2 + (zi - pos[j * 3 + 2]) ** 2;
      if (d < best) best = d;
    }
  }
  return Math.sqrt(best);
}

mkdirSync(OUT, { recursive: true });
const report: string[] = [
  "# Formation export report",
  "",
  `Generated by scripts/export-formations.ts — ${N} drones, ${FPS} fps, one loop each.`,
  "",
  "Concept animations from the website, exported as references. **Not flight-ready.** Real show drones fly at roughly 3–8 m/s and need about 2–3 m between them; anything outside that has to be slowed down, scaled up, or done with light (LEDs chasing along drones that hold still) in Skybrush.",
  "",
  "| Formation | Loop | Size (W×H×D m) | Max speed, lit | Max speed, any (incl. dark repositioning) | Min separation | To fly it |",
  "|---|---|---|---|---|---|---|",
];

for (const f of CULTURAL) {
  const dir = join(OUT, f.id);
  mkdirSync(dir, { recursive: true });
  const pos = new Float32Array(N * 3);
  const col = new Float32Array(N * 3);
  const prev = new Float32Array(N * 3);
  const prevLit = new Uint8Array(N);

  // --- point cloud, spec format, at its own 600-point sampling
  const cloudRig = f.build(CLOUD);
  const cp = new Float32Array(CLOUD * 3);
  const cc = new Float32Array(CLOUD * 3);
  f.pose(cloudRig, 0, cp, cc);
  const [cx, cy, cz] = centreOf(cp, CLOUD);
  const points: number[][] = [];
  const colors: number[][] = [];
  for (let i = 0; i < CLOUD; i++) {
    points.push([+(cp[i * 3] - cx).toFixed(2), +(cp[i * 3 + 1] - cy).toFixed(2), +(cp[i * 3 + 2] - cz).toFixed(2)]);
    colors.push([toSrgb(cc[i * 3]), toSrgb(cc[i * 3 + 1]), toSrgb(cc[i * 3 + 2])]);
  }
  writeFileSync(
    join(dir, `${f.id}.points.json`),
    JSON.stringify({ name: f.id, label: f.label, units: "metres", up: "y", centreAltitude: +cy.toFixed(1), points, colors })
  );

  // --- trajectories + stats
  const rig = f.build(N);
  const frames = Math.round(f.loop * FPS);
  const rows: string[][] = Array.from({ length: N }, () => ["Time_msec,x_m,y_m,z_m,Red,Green,Blue"]);
  let maxSpeed = 0;
  let maxLit = 0;
  let minSep = Infinity;
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity, minZ = Infinity, maxZ = -Infinity;
  for (let k = 0; k <= frames; k++) {
    const t = k / FPS;
    f.pose(rig, Math.min(t, f.loop - 1e-6), pos, col);
    for (let i = 0; i < N; i++) {
      const x = pos[i * 3], y = pos[i * 3 + 1], z = pos[i * 3 + 2];
      minX = Math.min(minX, x); maxX = Math.max(maxX, x);
      minY = Math.min(minY, y); maxY = Math.max(maxY, y);
      minZ = Math.min(minZ, z); maxZ = Math.max(maxZ, z);
      const lit = col[i * 3] + col[i * 3 + 1] + col[i * 3 + 2] > 0.15 ? 1 : 0;
      if (k > 0) {
        const v = Math.hypot(x - prev[i * 3], y - prev[i * 3 + 1], z - prev[i * 3 + 2]) * FPS;
        if (v > maxSpeed) maxSpeed = v;
        if (lit && prevLit[i] && v > maxLit) maxLit = v;
      }
      prevLit[i] = lit;
      // Blender/Skybrush: Z up. Ours: Y up, +Z toward the audience.
      rows[i].push(
        `${Math.round(t * 1000)},${x.toFixed(2)},${(-z).toFixed(2)},${y.toFixed(2)},${lin255(col[i * 3])},${lin255(col[i * 3 + 1])},${lin255(col[i * 3 + 2])}`
      );
    }
    if (k % Math.max(1, Math.round(FPS / 2)) === 0) minSep = Math.min(minSep, minSeparation(pos, col, N));
    prev.set(pos);
  }
  writeFileSync(
    join(dir, `${f.id}.skybrush.zip`),
    zip(rows.map((r, i) => ({ name: `Drone ${String(i + 1).padStart(4, "0")}.csv`, data: Buffer.from(r.join("\n") + "\n") })))
  );

  // --- preview SVG + static Skybrush formation, t=0
  f.pose(rig, 0, pos, col);
  const stat = ["Name,x_m,y_m,z_m,Red,Green,Blue"];
  for (let i = 0; i < N; i++) {
    stat.push(
      `Drone ${String(i + 1).padStart(4, "0")},${pos[i * 3].toFixed(2)},${(-pos[i * 3 + 2]).toFixed(2)},${pos[i * 3 + 1].toFixed(2)},${lin255(col[i * 3])},${lin255(col[i * 3 + 1])},${lin255(col[i * 3 + 2])}`
    );
  }
  writeFileSync(join(dir, `${f.id}.formation.csv`), stat.join("\n") + "\n");
  const S = 6;
  const w = (maxX - minX) * S + 40;
  const h = (maxY - minY) * S + 40;
  const dots: string[] = [];
  for (let i = 0; i < N; i++) {
    const r = toSrgb(col[i * 3]), g = toSrgb(col[i * 3 + 1]), b = toSrgb(col[i * 3 + 2]);
    if (r + g + b < 6) continue;
    dots.push(`<circle cx="${((pos[i * 3] - minX) * S + 20).toFixed(1)}" cy="${((maxY - pos[i * 3 + 1]) * S + 20).toFixed(1)}" r="3.2" fill="rgb(${r},${g},${b})"/>`);
  }
  writeFileSync(
    join(dir, `${f.id}.preview.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w.toFixed(0)} ${h.toFixed(0)}"><rect width="100%" height="100%" fill="#03040b"/>${dots.join("")}</svg>\n`
  );

  const verdict =
    maxSpeed <= 8 && minSep >= 2
      ? "Close to flyable as is"
      : [
          maxLit > 8 ? `slow ~${Math.ceil(maxLit / 8)}× or do fast parts in light` : "",
          maxSpeed > maxLit * 1.5 && maxSpeed > 8 ? "route the dark repositioning" : "",
          minSep < 2 ? `space out (closest pair ${minSep.toFixed(1)} m)` : "",
        ]
          .filter(Boolean)
          .join("; ");
  report.push(
    `| ${f.label} | ${f.loop}s | ${(maxX - minX).toFixed(0)}×${(maxY - minY).toFixed(0)}×${(maxZ - minZ).toFixed(0)} | ${maxLit.toFixed(1)} m/s | ${maxSpeed.toFixed(1)} m/s | ${minSep.toFixed(2)} m | ${verdict} |`
  );
  console.log(`${f.id}: ${N} drones, ${frames} frames, lit max ${maxLit.toFixed(1)} m/s, any ${maxSpeed.toFixed(1)} m/s, min sep ${minSep.toFixed(2)} m`);
}

report.push(
  "",
  "## Files",
  "",
  "- `<id>/<id>.points.json` — 600 points at t=0: metres, origin at the formation centre, Y up, sRGB colours. The Formation Asset Spec format.",
  "- `<id>/<id>.preview.svg` — the t=0 frame as coloured dots.",
  "- `<id>/<id>.skybrush.zip` — one loop, one CSV per drone, Skybrush Studio for Blender \"zipped CSV\" import: `Time_msec,x_m,y_m,z_m,Red,Green,Blue` (metres, Z up, linear colour 0–255). Formations panel → Import.",
  "- `<id>/<id>.formation.csv` — the t=0 frame as a static formation (Skybrush \"static CSV\" import: `Name,x_m,y_m,z_m,Red,Green,Blue`).",
  "",
  `Show-centre altitude used: ${SHOW_ALT} m.`
);
writeFileSync(join(OUT, "REPORT.md"), report.join("\n") + "\n");
console.log("wrote", OUT);
