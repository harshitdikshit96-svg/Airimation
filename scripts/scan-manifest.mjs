#!/usr/bin/env node
// Write src/lib/cultural/scans/manifest.ts: each scanned formation's small
// metadata (label, credit, licence, size) plus a loader for its heavy point
// data. The page ships only this manifest; a formation's points (~20 KB
// each, 1.3 MB for all of them) download the first time it is shown.
//
//   node scripts/scan-manifest.mjs
//
// Run after adding or re-converting a model (scan-to-formation.mjs,
// scan-colors.mjs). A unit test fails if the manifest is out of date.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "..", "src", "lib", "cultural", "scans");
// Work files (tmp-*, *-test) are not formations.
const files = readdirSync(dir).filter((f) => f.endsWith(".json") && !f.startsWith("tmp-") && !f.endsWith("-test.json")).sort();
const META = ["id", "label", "credit", "licence", "height", "width", "depth", "count", "quant"];

const rows = files.map((f) => {
  const json = JSON.parse(readFileSync(join(dir, f), "utf8"));
  const meta = Object.fromEntries(META.map((k) => [k, json[k]]));
  const file = f.replace(/\.json$/, "");
  return `  ${JSON.stringify(file)}: {\n    ...${JSON.stringify(meta)},\n    load: () => import("./${f}").then((m) => (m.default ?? m) as unknown as ScanFile),\n  },`;
});

writeFileSync(
  join(dir, "manifest.ts"),
  `// GENERATED by scripts/scan-manifest.mjs — do not edit by hand.
// Metadata for every scanned formation, and a loader for its point data
// (loaded on first use, so the page doesn't download every model up front).

import type { ScanFile, ScanSource } from "../scan";

export const SCAN_SOURCES: Record<string, ScanSource> = {
${rows.join("\n")}
};
`
);
console.log(`manifest: ${files.length} formations`);
